// Generates the tables in docs/code-structure.md (Procedures, Procedure 8).
//
// Run by Gradle on every build (see codestructure.gradle), or by hand:
//   java tools/CodeStructure.java src/main/java/frc/robot docs/code-structure.md
//
// It reads the Java source as text and finds subsystems, commands, bindings,
// autonomous routines, and CAN IDs by naming patterns. It only rewrites the
// part of the output file between the BEGIN/END GENERATED markers, so the
// hand-written overview above them is kept.

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;

public class CodeStructure {
  static final String BEGIN = "<!-- BEGIN GENERATED -->";
  static final String END = "<!-- END GENERATED -->";

  record Src(Path path, String rel, String text, String code) {}

  public static void main(String[] args) throws IOException {
    Path srcRoot = Path.of(args.length > 0 ? args[0] : "src/main/java/frc/robot");
    Path out = Path.of(args.length > 1 ? args[1] : "docs/code-structure.md");
    Path docsRoot = out.toAbsolutePath().getParent();
    Path repoRoot = docsRoot.getParent();

    List<Src> files;
    try (Stream<Path> walk = Files.walk(srcRoot)) {
      files = walk.filter(p -> p.toString().endsWith(".java")).sorted()
          .map(p -> read(p, repoRoot)).collect(Collectors.toList());
    }

    StringBuilder sb = new StringBuilder();
    sb.append(BEGIN).append("\n\n");
    sb.append("_Generated by `tools/CodeStructure.java` on every build. Don't edit by hand; edit the code and build._\n\n");

    // Subsystems
    Map<String, String[]> subsystems = new TreeMap<>(); // name -> {file, critical}
    Pattern subsystemDecl = Pattern.compile(
        "class\\s+(\\w+)\\s+(?:extends\\s+SubsystemBase\\b|extends\\s+\\w+(?:<[^>]*>)?\\s+implements\\s+[^{]*\\bSubsystem\\b|implements\\s+[^{]*\\bSubsystem\\b)");
    for (Src s : files) {
      Matcher m = subsystemDecl.matcher(s.code);
      if (m.find()) subsystems.put(m.group(1), new String[] {s.rel, isCritical(s.text, m.group(1)) ? "Yes" : "No"});
    }

    // Default commands in RobotContainer, matched to subsystem variables by type
    Src container = files.stream().filter(f -> f.path.getFileName().toString().equals("RobotContainer.java")).findFirst().orElse(null);
    Map<String, String> varToType = new LinkedHashMap<>();
    Map<String, String> defaults = new LinkedHashMap<>();
    if (container != null) {
      Matcher v = Pattern.compile("(?:final\\s+)?(\\w+)\\s+(\\w+)\\s*=").matcher(container.code);
      while (v.find()) varToType.put(v.group(2), v.group(1));
      Matcher d = Pattern.compile("(\\w+)\\.setDefaultCommand\\(").matcher(container.code);
      while (d.find()) {
        String type = varToType.getOrDefault(d.group(1), d.group(1));
        defaults.put(type, shorten(balanced(container.code, d.end() - 1)));
      }
    }

    sb.append("## Subsystems\n\n| Subsystem | File | Default command | Critical | Doc |\n| --- | --- | --- | --- | --- |\n");
    if (subsystems.isEmpty()) sb.append("| (none found) | | | | |\n");
    for (var e : subsystems.entrySet()) {
      String name = e.getKey();
      boolean critical = e.getValue()[1].equals("Yes");
      sb.append("| ").append(name).append(" | `").append(e.getValue()[0]).append("` | ")
          .append(cell(defaults.getOrDefault(name, "None"))).append(" | ").append(e.getValue()[1]).append(" | ")
          .append(docLink(docsRoot, "subsystems", name, critical)).append(" |\n");
    }

    // Commands: classes that extend a Command type, and Command factory methods
    sb.append("\n## Commands\n\n| Command | Kind | File | Requires | Critical | Doc |\n| --- | --- | --- | --- | --- | --- |\n");
    int commandRows = 0;
    Pattern cmdClass = Pattern.compile("class\\s+(\\w+)\\s+extends\\s+(\\w*Command\\w*)\\b");
    Pattern factory = Pattern.compile("public\\s+(static\\s+)?Command\\s+(\\w+)\\s*\\(");
    for (Src s : files) {
      Matcher c = cmdClass.matcher(s.code);
      if (c.find()) {
        String name = c.group(1);
        List<String> reqs = new ArrayList<>();
        Matcher r = Pattern.compile("addRequirements\\(([^)]*)\\)").matcher(s.code);
        while (r.find()) reqs.add(r.group(1).trim());
        boolean critical = isCritical(s.text, name);
        sb.append("| ").append(name).append(" | Class | `").append(s.rel).append("` | ")
            .append(cell(reqs.isEmpty() ? "None declared" : String.join(", ", reqs))).append(" | ")
            .append(critical ? "Yes" : "No").append(" | ").append(docLink(docsRoot, "commands", name, critical)).append(" |\n");
        commandRows++;
      }
      String owner = className(s.code);
      boolean inSubsystem = subsystems.containsKey(owner);
      Matcher f = factory.matcher(s.code);
      while (f.find()) {
        String method = f.group(2);
        if (method.equals("getAutonomousCommand")) continue;
        sb.append("| ").append(owner).append(".").append(method).append("() | Factory | `").append(s.rel).append("` | ")
            .append(inSubsystem && f.group(1) == null ? owner : "See method").append(" | No | \u2014 |\n");
        commandRows++;
      }
    }
    if (commandRows == 0) sb.append("| (none found) | | | | | |\n");

    // Controller and mode bindings
    sb.append("\n## Bindings\n\n| Trigger | Type | Command |\n| --- | --- | --- |\n");
    int bindingRows = 0;
    if (container != null) {
      Matcher b = Pattern.compile("\\.(onTrue|onFalse|whileTrue|whileFalse|toggleOnTrue|toggleOnFalse)\\(").matcher(container.code);
      while (b.find()) {
        int start = Math.max(Math.max(container.code.lastIndexOf(';', b.start()), container.code.lastIndexOf('{', b.start())),
            container.code.lastIndexOf('}', b.start())) + 1;
        String trigger = squash(container.code.substring(start, b.start()));
        sb.append("| `").append(trigger).append("` | ").append(b.group(1)).append(" | ")
            .append(cell(shorten(balanced(container.code, b.end() - 1)))).append(" |\n");
        bindingRows++;
      }
    }
    if (bindingRows == 0) sb.append("| (none found) | | |\n");

    // Autonomous routines: getAutonomousCommand plus static factories in classes named *Auto*
    sb.append("\n## Autonomous routines\n\n| Routine | File | Steps |\n| --- | --- | --- |\n");
    int autoRows = 0;
    for (Src s : files) {
      String owner = className(s.code);
      Matcher a = Pattern.compile("public\\s+(?:static\\s+)?Command\\s+(\\w+)\\s*\\([^)]*\\)\\s*\\{").matcher(s.code);
      while (a.find()) {
        String method = a.group(1);
        if (!method.equals("getAutonomousCommand") && !owner.contains("Auto")) continue;
        String body = balancedBraces(s.code, a.end() - 1);
        List<String> steps = new ArrayList<>();
        Matcher call = Pattern.compile("\\.(\\w+)\\(|new\\s+(\\w+)\\(").matcher(body);
        while (call.find()) {
          String n = call.group(1) != null ? call.group(1) : "new " + call.group(2);
          if (n.startsWith("with") || n.equals("of") || n.equals("sequence") || n.equals("parallel")) continue;
          if (steps.isEmpty() || !steps.get(steps.size() - 1).equals(n)) steps.add(n);
        }
        sb.append("| ").append(owner).append(".").append(method).append("() | `").append(s.rel).append("` | ")
            .append(cell(String.join(" \u2192 ", steps))).append(" |\n");
        autoRows++;
      }
    }
    if (autoRows == 0) sb.append("| (none found) | | |\n");

    // CAN IDs: int constants whose names end in Id, ID, or _CAN_ID
    sb.append("\n## CAN IDs\n\n| Constant | ID | File |\n| --- | --- | --- |\n");
    Map<Integer, List<String>> byId = new TreeMap<>();
    List<String[]> ids = new ArrayList<>();
    Pattern idConst = Pattern.compile("int\\s+(\\w*(?:Id|ID|_CAN_ID))\\s*=\\s*(\\d+)\\s*;");
    for (Src s : files) {
      Matcher m = idConst.matcher(s.code);
      while (m.find()) {
        ids.add(new String[] {m.group(1), m.group(2), s.rel});
        byId.computeIfAbsent(Integer.parseInt(m.group(2)), k -> new ArrayList<>()).add(m.group(1));
      }
    }
    ids.sort((x, y) -> Integer.compare(Integer.parseInt(x[1]), Integer.parseInt(y[1])));
    for (String[] id : ids) sb.append("| ").append(id[0]).append(" | ").append(id[1]).append(" | `").append(id[2]).append("` |\n");
    if (ids.isEmpty()) sb.append("| (none found) | | |\n");
    List<String> dupes = byId.entrySet().stream().filter(e -> e.getValue().size() > 1)
        .map(e -> e.getKey() + " (" + String.join(", ", e.getValue()) + ")").collect(Collectors.toList());
    sb.append("\n").append(dupes.isEmpty() ? "No duplicate CAN IDs found."
        : "**DUPLICATE CAN IDs:** " + String.join("; ", dupes) + ". Devices of different types may share an ID; check each one.").append("\n");

    sb.append("\n").append(END).append("\n");

    String existing = Files.exists(out) ? Files.readString(out, StandardCharsets.UTF_8).replace("\r\n", "\n") : "";
    String result;
    int b = existing.indexOf(BEGIN), e = existing.indexOf(END);
    if (b >= 0 && e > b) {
      result = existing.substring(0, b) + sb + existing.substring(e + END.length()).replaceFirst("^\n", "");
    } else {
      result = "# Code structure\n\n## Overview\n\n(Write a short overview of the robot here. Keep it above the generated part.)\n\n" + sb;
    }
    if (!result.equals(existing)) {
      Files.createDirectories(out.toAbsolutePath().getParent());
      Files.writeString(out, result, StandardCharsets.UTF_8);
      System.out.println("Updated " + out);
    } else {
      System.out.println(out + " is up to date");
    }
  }

  static Src read(Path p, Path repoRoot) {
    try {
      String text = Files.readString(p, StandardCharsets.UTF_8).replace("\r\n", "\n");
      String rel = repoRoot.relativize(p.toAbsolutePath()).toString().replace('\\', '/');
      return new Src(p, rel, text, stripComments(text));
    } catch (IOException ex) {
      throw new RuntimeException(ex);
    }
  }

  /** Removes // and block comments (outside string literals). */
  static String stripComments(String s) {
    StringBuilder out = new StringBuilder();
    boolean str = false, chr = false;
    for (int i = 0; i < s.length(); i++) {
      char c = s.charAt(i);
      char n = i + 1 < s.length() ? s.charAt(i + 1) : 0;
      if (str || chr) {
        out.append(c);
        if (c == '\\') { out.append(n); i++; }
        else if (str && c == '"') str = false;
        else if (chr && c == '\'') chr = false;
      } else if (c == '"') { str = true; out.append(c); }
      else if (c == '\'') { chr = true; out.append(c); }
      else if (c == '/' && n == '/') { while (i < s.length() && s.charAt(i) != '\n') i++; out.append('\n'); }
      else if (c == '/' && n == '*') { int end = s.indexOf("*/", i + 2); i = end < 0 ? s.length() : end + 1; out.append(' '); }
      else out.append(c);
    }
    return out.toString();
  }

  /** True if a "// @critical" comment appears in the lines just above the class declaration. */
  static boolean isCritical(String text, String className) {
    Matcher m = Pattern.compile("(?m)^.*\\bclass\\s+" + Pattern.quote(className) + "\\b").matcher(text);
    if (!m.find()) return false;
    String before = text.substring(0, m.start());
    String[] lines = before.split("\n");
    for (int i = lines.length - 1; i >= 0 && i >= lines.length - 15; i--) {
      String l = lines[i].trim();
      if (l.matches("//\\s*@critical\\b.*")) return true;
      if (l.isEmpty() || l.startsWith("*") || l.startsWith("/*") || l.startsWith("//") || l.startsWith("@")) continue;
      break;
    }
    return false;
  }

  static String className(String code) {
    Matcher m = Pattern.compile("\\bclass\\s+(\\w+)").matcher(code);
    return m.find() ? m.group(1) : "?";
  }

  /** Text inside the parentheses starting at index open. */
  static String balanced(String s, int open) {
    int depth = 0;
    for (int i = open; i < s.length(); i++) {
      char c = s.charAt(i);
      if (c == '(') depth++;
      else if (c == ')' && --depth == 0) return s.substring(open + 1, i);
    }
    return s.substring(open + 1);
  }

  static String balancedBraces(String s, int open) {
    int depth = 0;
    for (int i = open; i < s.length(); i++) {
      char c = s.charAt(i);
      if (c == '{') depth++;
      else if (c == '}' && --depth == 0) return s.substring(open + 1, i);
    }
    return s.substring(open + 1);
  }

  static String squash(String s) {
    return s.replaceAll("\\s+", " ").trim();
  }

  static String shorten(String s) {
    s = squash(s);
    return s.length() > 90 ? s.substring(0, 87) + "..." : s;
  }

  static String cell(String s) {
    return s.isEmpty() ? "\u2014" : "`" + s.replace("|", "\\|").replace("`", "'") + "`";
  }

  static String docLink(Path docsRoot, String folder, String name, boolean critical) {
    if (Files.exists(docsRoot.resolve(folder).resolve(name + ".md"))) {
      return "[" + folder + "/" + name + ".md](" + folder + "/" + name + ".md)";
    }
    return critical ? "**MISSING**" : "\u2014";
  }
}
